// Ensure database connection
if (!isset($pdo) || !$pdo instanceof PDO) {
    die("FATAL ERROR: Database connection (\$pdo) is not available.");
}

// Check Admin permissions
if (!is_admin()) {
    die("Access Denied: Admins only.");
}

// Default filter dates
$from   = $_GET['from'] ?? date('Y-m-01');
$to     = $_GET['to']   ?? date('Y-m-d');
$export = $_GET['export'] ?? '';

function clean_ksh($amount) {
    return is_numeric($amount) ? number_format((float)$amount, 2, '.', '') : '0.00'; 
}

// SQL QUERY: Fetch ALL bookings (No Host Filter)
$sql = "
SELECT 
    b.*, 
    r.name AS room_name, 
    u.full_name AS tenant_name,
    u.id AS tenant_id
FROM bookings b
LEFT JOIN rooms r ON r.id = b.room_id
LEFT JOIN users u ON u.id = b.tenant_id
WHERE b.created_at BETWEEN :from AND :to
ORDER BY b.created_at DESC
";

try {
    $stmt = $pdo->prepare($sql);
    $stmt->execute([
        ':from' => $from . ' 00:00:00',
        ':to'   => $to   . ' 23:59:59',
    ]);
    $rows = $stmt->fetchAll(PDO::FETCH_ASSOC);
} catch (PDOException $e) {
    die("Database Error: " . $e->getMessage());
}

// ----------------------------------------------------
// 2. EXPORT LOGIC (Before HTML Output)
// ----------------------------------------------------

// --- A. EXPORT TO CSV ---
if ($export === 'csv') {
    if (ob_get_level()) ob_end_clean(); // Clean buffer
    
    header('Content-Type: text/csv');
    header('Content-Disposition: attachment; filename="admin_bookings_report_' . date('Y-m-d') . '.csv"');
    header('Pragma: no-cache');
    header('Expires: 0');
    
    $out = fopen('php://output', 'w');
    
    // Header Row
    fputcsv($out, ['Ref Code', 'Client Name', 'House Name', 'Check-in', 'Check-out', 'Total KSh', 'Status', 'Date Booked']);
    
    foreach ($rows as $b) {
        fputcsv($out, [
            $b['ref_code'],
            $b['tenant_name'],
            $b['room_name'],
            $b['checkin_date'],
            $b['checkout_date'],
            clean_ksh($b['total_amount_ksh']),
            $b['status'],
            $b['created_at']
        ]);
    }
    fclose($out);
    exit; // Stop execution
}

